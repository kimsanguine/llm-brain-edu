"""메모에 개인정보가 섞여 들어갈 때 그 자리에서 알려 준다.

왜 필요한가
-----------
README 와 교안은 "주민번호·계좌가 든 자료는 넣지 마세요"라고 이미 말한다.
그런데 문서를 읽는 시점과 실수하는 시점이 다르다. 실수는 메모를 넣는 순간에
일어나므로, 경고도 그 순간에 나와야 한다.

특히 LIVE 경로는 메모 본문을 그대로 LLM API 로 보낸다. 로컬 파일에 남는 것과
외부로 나가는 것은 무게가 다르다.

막지 않는 이유
--------------
막으면 정당한 메모까지 막힌다("주민번호는 앞 6자리가 생년월일이다" 같은 설명,
테스트용 더미 값). 무엇을 넣을지는 사람이 정한다. 도구는 놓치지 않게만 한다.

오탐을 줄이려고 형식이 뚜렷한 둘만 본다. 계좌번호는 은행마다 자릿수가 달라
일반 숫자와 구분이 안 되고, 전화번호는 오탐이 잦아 넣지 않았다.
"""
from __future__ import annotations

import re

# 주민등록번호 — 하이픈을 빼고 붙여 쓰는 사람이 많아 둘 다 본다.
# 앞 6자리가 실제 날짜(YYMMDD) 형식일 때만 본다. 그냥 13자리 숫자를 다 잡으면
# 주문번호·타임스탬프가 걸려서, 경고가 잦아지고 학생이 경고를 안 읽게 된다.
# 뒤 첫 자리는 1~4(내국인) 또는 5~8(외국인).
_RRN = re.compile(
    r"(?<!\d)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])\s?[-–]?\s?[1-8]\d{6}(?!\d)"
)
# 카드번호 — 4자리씩 네 묶음
_CARD = re.compile(r"(?<!\d)\d{4}[\s-]\d{4}[\s-]\d{4}[\s-]\d{4}(?!\d)")

PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("주민등록번호", _RRN),
    ("카드번호", _CARD),
]


def find_pii(text: str) -> list[str]:
    """찾은 개인정보의 종류 이름을 돌려준다. 값 자체는 담지 않는다.

    값을 돌려주면 그걸 출력하는 쪽에서 로그·터미널에 다시 남는다.
    """
    return [name for name, pat in PATTERNS if pat.search(text or "")]


def warn_if_pii(text: str, where: str) -> list[str]:
    """찾으면 화면에 알리고, 찾은 종류를 돌려준다(없으면 빈 목록)."""
    found = find_pii(text)
    if not found:
        return []
    print(f"\n  ⚠️  {where}에 {' · '.join(found)}로 보이는 값이 있습니다.")
    print("     저장은 했지만, 다음 두 가지를 확인하세요.")
    print("     · 키를 넣고 컴파일하면 이 내용이 그대로 AI 서비스로 전송됩니다.")
    print("     · 브레인 폴더를 공유하거나 GitHub 에 올리면 함께 나갑니다.")
    print("     지워야 한다면 raw 파일을 고친 뒤 compile.py를 실행하세요. 이전 버전 자료는 --recompile이 필요합니다.\n")
    print("     이전 버전의 episodes 기록과 공유본 정리는 README_수강생용.md를 확인하세요.\n")
    return found
